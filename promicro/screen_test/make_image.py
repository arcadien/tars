"""TARS - build src/image.h for the screen test (Pro Micro: 32 KB flash).

The photo is cropped square, shrunk to 120 x 120 and quantised to 16 colours
(4 bits per pixel, 7.2 KB); the sketch doubles every pixel to fill 240 x 240.

    uv run make_image.py [image] [left top size]
Default: ../../references/film_still_tars.jpeg, crop 380 40 620 (Cooper + TARS).
"""
import sys
from pathlib import Path
from PIL import Image

HERE = Path(__file__).parent
SIDE = 120

args = sys.argv[1:]
src = Path(args[0]) if args else HERE / "../../references/film_still_tars.jpeg"
left, top, size = map(int, args[1:4]) if len(args) >= 4 else (380, 40, 620)

im = Image.open(src).convert("RGB").crop((left, top, left + size, top + size))
im = im.resize((SIDE, SIDE), Image.LANCZOS)
q = im.quantize(colors=16, dither=Image.FLOYDSTEINBERG)
pal = q.getpalette()[:48]
pal += [0] * (48 - len(pal))
px = list(q.tobytes())

def rgb565(r, g, b):
    return (r & 0xF8) << 8 | (g & 0xFC) << 3 | b >> 3

out = [
    f"// Generated by make_image.py from {src.name} (crop {left} {top} {size}), do not edit.",
    "#pragma once",
    "#include <avr/pgmspace.h>",
    f"static const uint8_t IMG_SIDE = {SIDE};",
    "static const uint16_t IMG_PALETTE[16] PROGMEM = {",
    "  " + ", ".join(f"0x{rgb565(*pal[i*3:i*3+3]):04X}" for i in range(16)),
    "};",
    f"// two pixels per byte, high nibble first, {SIDE * SIDE // 2} bytes",
    f"static const uint8_t IMG_PIXELS[{SIDE * SIDE // 2}] PROGMEM = {{",
]
packed = [px[i] << 4 | px[i + 1] for i in range(0, len(px), 2)]
for i in range(0, len(packed), 24):
    out.append("  " + ", ".join(f"0x{b:02X}" for b in packed[i:i + 24]) + ",")
out.append("};")
(HERE / "src/image.h").write_text("\n".join(out) + "\n")
q.convert("RGB").resize((SIDE * 2, SIDE * 2), Image.NEAREST).save(HERE / "preview.png")
print(f"src/image.h: {len(packed)} bytes, preview.png")
