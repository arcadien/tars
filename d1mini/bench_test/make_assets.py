"""TARS - build the D1 mini bench test assets (src/image.h, src/sound.h).

    uv run make_assets.py [--image FILE --crop LEFT TOP SIZE] [--mp3 FILE] [--seconds S]

Image: cropped square, 240 x 240 RGB565 (115 KB of flash).
  Default ../../references/film_still_tars.jpeg, crop 380 40 620 (Cooper + TARS).
Sound: --mp3 keeps the first ~S seconds of your file (cut on a frame boundary,
  the decoder resyncs); without it, a synthetic 5 s jingle (arpeggio, chord,
  sweep, beeps) encoded mono 22.05 kHz 48 kbit/s.
"""
import argparse
import math
import struct
from pathlib import Path
from PIL import Image

HERE = Path(__file__).parent
SIDE = 240


def c_array(name, data, per_line=24):
    lines = [f"static const uint8_t {name}[{len(data)}] PROGMEM = {{"]
    for i in range(0, len(data), per_line):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + per_line]) + ",")
    lines.append("};")
    return lines


def make_image(src, left, top, size):
    im = Image.open(src).convert("RGB").crop((left, top, left + size, top + size))
    im = im.resize((SIDE, SIDE), Image.LANCZOS)
    data = bytearray()
    px = im.tobytes()
    for i in range(0, len(px), 3):
        r, g, b = px[i:i + 3]
        data += struct.pack(">H", (r & 0xF8) << 8 | (g & 0xFC) << 3 | b >> 3)  # big endian = SPI order
    out = [f"// Generated by make_assets.py from {src.name} (crop {left} {top} {size}), do not edit.",
           "#pragma once", "#include <pgmspace.h>",
           f"static const uint16_t IMG_SIDE = {SIDE};",
           "// RGB565, big endian (sent as is over SPI), row by row"]
    (HERE / "src/image.h").write_text("\n".join(out + c_array("IMG_RGB565", data)) + "\n")
    im.save(HERE / "preview.png")
    return len(data)


def jingle(rate):
    """Original test jingle: A minor arpeggio, chord, rising sweep, three beeps."""
    samples = []

    def tone(freqs, dur, vol=0.5, sweep_to=None):
        n = int(dur * rate)
        phase = [0.0] * len(freqs)
        for i in range(n):
            env = min(1, i / (0.01 * rate)) * min(1, (n - i) / (0.05 * rate))
            v = 0.0
            for k, f in enumerate(freqs):
                if sweep_to:
                    f = f + (sweep_to - f) * i / n
                phase[k] += 2 * math.pi * f / rate
                v += math.sin(phase[k]) + 0.3 * math.sin(2 * phase[k])
            samples.append(vol * env * v / len(freqs) / 1.3)

    def rest(dur):
        samples.extend([0.0] * int(dur * rate))

    for f in (220, 261.6, 329.6, 440, 523.3, 659.3):
        tone([f], 0.18)
    tone([220, 261.6, 329.6, 440], 1.2, 0.6)
    rest(0.15)
    tone([200], 1.0, 0.4, sweep_to=2000)
    rest(0.15)
    for _ in range(3):
        tone([1000], 0.12, 0.5)
        rest(0.12)
    return samples


def make_sound(mp3, seconds):
    if mp3:
        data = Path(mp3).read_bytes()
        # rough cut: keep bytes for `seconds` at the file's average bitrate (assume 128 kbit/s if unknown)
        data = data[: int(seconds * 128000 / 8)] if len(data) > seconds * 16000 else data
        label = f"first ~{seconds} s of {Path(mp3).name}"
    else:
        import lameenc
        rate = 22050
        pcm = b"".join(struct.pack("<h", int(max(-1, min(1, s)) * 32000)) for s in jingle(rate))
        enc = lameenc.Encoder()
        enc.set_bit_rate(48)
        enc.set_in_sample_rate(rate)
        enc.set_channels(1)
        enc.set_quality(2)
        data = enc.encode(pcm) + enc.flush()
        label = "synthetic jingle, mono 22.05 kHz 48 kbit/s"
    out = [f"// Generated by make_assets.py: {label}, do not edit.",
           "#pragma once", "#include <pgmspace.h>"]
    (HERE / "src/sound.h").write_text("\n".join(out + c_array("SOUND_MP3", data)) + "\n")
    return len(data)


ap = argparse.ArgumentParser()
ap.add_argument("--image", default=HERE / "../../references/film_still_tars.jpeg", type=Path)
ap.add_argument("--crop", nargs=3, type=int, default=(380, 40, 620))
ap.add_argument("--mp3")
ap.add_argument("--seconds", type=float, default=8)
ap.add_argument("--only", choices=("image", "sound"))
a = ap.parse_args()
if a.only != "sound":
    print(f"src/image.h: {make_image(a.image, *a.crop)} bytes (preview.png)")
if a.only != "image":
    print(f"src/sound.h: {make_sound(a.mp3, a.seconds)} bytes")
